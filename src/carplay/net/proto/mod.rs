//! The binary plists carried on the control and event channels.
//!
//! Every control-plane payload that is not TLV8 (pairing) or opaque (`/auth-setup`) is an
//! Apple binary plist with content type [`CONTENT_TYPE`]. This module is the typed data
//! model for all of them, keyed to the Accessory Interface Specification R29 tables:
//!
//! | Module | Spec | URL / method |
//! | --- | --- | --- |
//! | [`info`] | §30.3.2.4, Tables 30-27..30-43 | `GET /info` |
//! | [`setup`] | §30.3.2.5, Tables 30-44..30-54 | `SETUP` |
//! | [`feedback`] | §30.3.2.6, Tables 30-56, 30-57 | `POST /feedback` |
//! | [`command`] | §30.3.7, Tables 30-73..30-93 | `POST /command` |
//! | [`modes`] | §30.3.3, §30.3.4, Tables 30-59..30-65 | shared by `/info` and `/command` |
//!
//! # Conventions
//!
//! **Unknown keys are ignored.** Head units send keys that are not in R29 (`features`,
//! `timestampInfo`, `uuid` on a screen stream) and future ones will send more. Deriving
//! `Deserialize` without `deny_unknown_fields` is deliberate: an unrecognised key must
//! never fail a session.
//!
//! **Unknown enum values are preserved, not rejected.** Every enum here is generated by
//! [`carplay_enum!`] and carries an `Other(i64)` arm. A head unit that invents a
//! `resourceID` should not take the whole `/info` parse down with it, and the value still
//! round-trips unchanged if we echo it back.
//!
//! **Optional means optional on the wire.** Fields the spec marks `N` are `Option<T>` with
//! `skip_serializing_if`, so an absent value is an absent key rather than a null.
//!
//! **Scalar flexibility follows the destination type.** Numbers and booleans accept
//! compatible strings through [`from_binary`] and [`from_value`]; ordinary strings and
//! raw [`plist::Value`] payloads retain their original values.
//!
//! **Integers are signed.** plist has one integer type and iOS puts genuinely negative
//! values in it — iOS 14.6 sends `streamConnectionID = -8950532481248312265`. Everything
//! numeric is `i64`/`f64` for that reason; see [`setup::StreamRequest::connection_id`] for
//! the one place the signedness actually matters.

use anyhow::{Context, Result, anyhow};
use log::debug;
use serde::{Serialize, de::DeserializeOwned};

pub mod command;
pub mod feedback;
pub mod flexible;
pub mod info;
pub mod modes;
pub mod setup;

/// The MIME type every plist body on the control and event channels carries.
pub const CONTENT_TYPE: &str = "application/x-apple-binary-plist";

/// Encode a message as a binary plist, ready for a request or response body.
pub fn to_binary<T: Serialize>(value: &T) -> Result<Vec<u8>> {
	let mut out = Vec::new();
	plist::to_writer_binary(&mut out, value).context("failed to encode a plist")?;
	Ok(out)
}

/// Decode a message from a body. Accepts binary or XML, because `plist` sniffs the header
/// and a head unit that answers in XML is easier to accept than to argue with.
pub fn from_binary<T: DeserializeOwned>(bytes: &[u8]) -> Result<T> {
	let value: plist::Value = plist::from_bytes(bytes).context("failed to decode a plist")?;
	from_value(&value)
}

/// Decode a parsed plist with CarPlay scalar flexibility. Raw values and strings are
/// preserved; numeric and boolean conversions follow the destination Rust type.
pub fn from_value<T: DeserializeOwned>(value: &plist::Value) -> Result<T> {
	flexible::from_value(value).map_err(|err| {
		// Keep the original wire values available when a typed decode fails.
		let mut xml = Vec::new();
		match plist::to_writer_xml(&mut xml, value) {
			Ok(()) => debug!(
				"plist that failed to decode:\n{}",
				String::from_utf8_lossy(&xml)
			),
			Err(err) => debug!("plist that failed to decode could not be re-encoded: {err}"),
		}
		anyhow!(err).context("failed to decode a plist")
	})
}

/// Define an enum that survives values it has never heard of.
///
/// The spec's enums are closed sets, but we are talking to third-party firmware over a
/// reverse-engineered protocol. Every generated enum gets an `Other(i64)` arm so an
/// unrecognised value parses, logs legibly, and re-serialises to exactly the number that
/// arrived.
#[macro_export]
macro_rules! carplay_enum {
	(
		$(#[$meta:meta])*
		$name:ident {
			$( $(#[$variant_meta:meta])* $variant:ident = $value:expr ),* $(,)?
		}
	) => {
		$(#[$meta])*
		#[derive(Clone, Copy, Debug, PartialEq, Eq, ::serde::Serialize, ::serde::Deserialize)]
		#[serde(from = "i64", into = "i64")]
		pub enum $name {
			$( $(#[$variant_meta])* $variant, )*
			/// A value that is not in R29. Kept verbatim so it round-trips.
			Other(i64),
		}

		impl From<i64> for $name {
			fn from(value: i64) -> Self {
				match value {
					$( $value => Self::$variant, )*
					other => Self::Other(other),
				}
			}
		}

		impl From<$name> for i64 {
			fn from(value: $name) -> Self {
				match value {
					$( $name::$variant => $value, )*
					$name::Other(other) => other,
				}
			}
		}
	};
}

